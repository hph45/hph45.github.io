// Build interaction geometry only. Never rerun the historical city migration.
// Source: Natural Earth 1:110m countries, public domain.
import { readFile, writeFile } from "node:fs/promises";
import { geoPath, geoCentroid } from "d3-geo";
import { worldProjection } from "../matchmaking/src/map.js";

const [input] = process.argv.slice(2);
if (!input) throw new Error("Usage: node scripts/build-map-countries.mjs countries.geojson");
const source = JSON.parse(await readFile(input, "utf8"));
const names = new Intl.DisplayNames(["en"], { type: "region" });
const path = geoPath(worldProjection()).digits(2);
const shapes = source.features.flatMap(feature => {
  const code = ({ CYN: "CY", SOL: "SO" })[feature.properties.ADM0_A3] || feature.properties.ISO_A2_EH;
  if (!/^[A-Z]{2}$/.test(code)) throw new Error(`Missing country code: ${feature.properties.ADMIN}`);
  // GeoNames lists French Guiana and Svalbard separately. Split those existing
  // polygons without altering the outline or assigning their readers to Europe.
  const groups = new Map();
  const polygons = feature.geometry.type === "MultiPolygon" ? feature.geometry.coordinates : [feature.geometry.coordinates];
  for (const coordinates of polygons) {
    const [longitude, latitude] = geoCentroid({ type: "Polygon", coordinates });
    const region = code === "FR" && longitude < -40 ? "GF" : code === "NO" && latitude > 75 ? "SJ" : code;
    if (!groups.has(region)) groups.set(region, []);
    groups.get(region).push(coordinates);
  }
  return [...groups].map(([region, coordinates]) => {
    const geometry = { type: "MultiPolygon", coordinates };
    const largest = coordinates.map(coordinates => ({ type: "Polygon", coordinates })).sort((a, b) => path.area(b) - path.area(a))[0];
    return { country: names.of(region), path: path(geometry), center: path.centroid(largest).map(value => Number(value.toFixed(2))) };
  });
});
await writeFile(new URL("../matchmaking/src/country-shapes.js", import.meta.url),
  "// Generated by scripts/build-map-countries.mjs. Natural Earth, public domain.\n"
  + "// https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_admin_0_countries.geojson\n"
  + `export const COUNTRY_SHAPES = ${JSON.stringify(shapes)};\n`);
console.log(`Built ${shapes.length} country shapes.`);
